"""Java backend: the APERuntime launch contract and the Android-safe runtime.

None of these tests needs a real APE. Generation only copies the binary, so a file
with the APE magic is enough, and the behavioural tests drive the generated
APEClient with the JVM itself standing in for the APE.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from apebind.backends.java import JavaGenerator
from apebind.schema import SchemaCodec


JAVA = shutil.which('java')
JAVAC = shutil.which('javac')
PROJECT_ROOT = Path(__file__).resolve().parents[3]
SOURCE_PACKAGE = Path('src') / 'main' / 'java' / 'apebind' / 'generated' / 'fixturebind'
MARKER = '// Generated by APEBind. Do not edit directly.'

# Java 9+ APIs that Android (API 26, no core library desugaring) does not provide.
ANDROID_MISSING_APIS = (
    'Files.readString(',
    'Path.of(',
    '.readAllBytes()',
    'ProcessHandle',
    'toString(StandardCharsets',
    ').toList()',
)


def generate_with_synthetic_ape(tmp_path: Path) -> Path:
    ape_path = tmp_path / 'fixture.com'
    ape_path.write_bytes(b"MZqFpD='synthetic")
    spec = SchemaCodec().load(PROJECT_ROOT / 'examples' / 'fixture.apebind.yaml')
    output_directory = tmp_path / 'generated-java'
    JavaGenerator().generate(spec, ape_path, output_directory)

    return output_directory / SOURCE_PACKAGE


def read_source(source_directory: Path, name: str) -> str:
    return (source_directory / name).read_text(encoding='utf-8')


def test_java_backend_renders_the_launch_runtime(tmp_path: Path):
    sources = generate_with_synthetic_ape(tmp_path)

    runtime = read_source(sources, 'APERuntime.java')
    processes = read_source(sources, 'Processes.java')

    assert runtime.startswith(MARKER)
    assert 'public final class APERuntime' in runtime
    for accessor in ('binary()', 'launcher()', 'shellWrapper()', 'workingDirectory()', 'environment()', 'toBuilder()'):
        assert f'public {accessor}' not in runtime  # accessors carry a return type
        assert accessor in runtime
    assert 'public static APERuntime defaults()' in runtime
    assert processes.startswith(MARKER)
    assert 'static long pid(Process process)' in processes
    assert 'static void destroyTree(Process process, boolean forcibly)' in processes


def test_java_binding_is_created_from_a_runtime(tmp_path: Path):
    sources = generate_with_synthetic_ape(tmp_path)

    binding = read_source(sources, 'FixturebindBinding.java')

    assert 'public static FixturebindBinding defaults()' in binding
    assert 'public static FixturebindBinding create(APERuntime runtime)' in binding
    assert 'public APERuntime runtime()' in binding
    assert 'static final APEClient CLIENT' not in binding
    assert 'public String echo(EchoParameters parameters)' in binding
    assert 'return (String) client.invoke(' in binding
    assert 'public ProcessSession serve(\n        ServeParameters parameters,\n        InputStream stdinSource\n    )' in binding
    assert 'public ProcessSession rawPersistent(List<?> arguments)' in binding
    assert 'Objects.requireNonNull(parameters, "parameters");\n\n        return' in binding


def test_java_client_and_session_expose_the_launch_contract(tmp_path: Path):
    sources = generate_with_synthetic_ape(tmp_path)

    client = read_source(sources, 'APEClient.java')
    session = read_source(sources, 'ProcessSession.java')
    json_source = read_source(sources, 'Json.java')

    assert 'public APEClient(\n        String binaryName,\n        APERuntime runtime,' in client
    assert 'public APEClient(Path binaryPath, Map<String, Object> operations, Map<String, Object> policy)' in client
    assert 'public APERuntime runtime()' in client
    assert 'public List<String> commandLine(List<String> argv)' in client
    assert 'public Map<String, String> environment()' in client
    assert 'builder.directory(runtime.workingDirectory().toFile());' in client
    assert 'session.deferResult(() -> waitForJsonResult(' in client
    assert 'Processes.destroyTree(' in client
    assert 'Process process = spawn(argv);\n\n        CompletableFuture<String> stdout' in client
    assert 'return Processes.pid(process);' in session
    for member in (
        'public ProcessSession onStdoutLine(Consumer<String> listener)',
        'public ProcessSession onStderrLine(Consumer<String> listener)',
        'public ProcessSession onStdoutPrompt(Consumer<String> listener)',
        'void deferResult(Supplier<Object> supplier)',
        'Processes.destroyTree(process, forcibly)',
        'destination.flush();',
    ):
        assert member in session
    assert 'stderrCollector.await(stoppedByClient);\n\n            waitForEventChannel();' in session
    assert 'public static String stringify(Object value)' in json_source


def strip_java_comments(text: str) -> str:
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.DOTALL)

    return re.sub(r'//[^\n]*', '', text)


def test_java_runtime_avoids_apis_missing_on_android(tmp_path: Path):
    sources = generate_with_synthetic_ape(tmp_path)

    for path in sorted(sources.glob('*.java')):
        code = strip_java_comments(path.read_text(encoding='utf-8'))
        for api in ANDROID_MISSING_APIS:
            assert api not in code, f'{path.name} uses {api}'


@pytest.mark.skipif(JAVA is None or JAVAC is None, reason='Java 17+ is not installed')
def test_java_runtime_launches_through_a_runtime_and_streams_output(tmp_path: Path):
    sources = generate_with_synthetic_ape(tmp_path)
    classes_directory = tmp_path / 'classes'
    classes_directory.mkdir()
    generated = sorted(sources.glob('*.java'))
    subprocess.run(
        [JAVAC, '--release', '17', '-Xlint:all', '-Werror', '-d', str(classes_directory), *map(str, generated)],
        check=True,
        capture_output=True,
        text=True,
        encoding='utf-8',
        errors='replace',
        timeout=120,
    )

    prompter = tmp_path / 'Prompter.java'
    prompter.write_text(
        '''
public class Prompter {
    public static void main(String[] args) throws Exception {
        System.out.println("first");
        System.out.println("second");
        System.out.print("code: ");
        System.out.flush();
        Thread.sleep(1500);
        System.out.println();
        System.out.println(System.getenv("APEBIND_RUNTIME_TEST") + "|" + System.getenv("APEBIND_TEST_SECRET"));
    }
}
''',
        encoding='utf-8',
    )
    main = tmp_path / 'Main.java'
    main.write_text(
        '''
import apebind.generated.fixturebind.APEClient;
import apebind.generated.fixturebind.APERuntime;
import apebind.generated.fixturebind.ProcessSession;
import java.nio.file.Paths;
import java.util.List;
import java.util.Map;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;

public class Main {
    public static void main(String[] args) throws Exception {
        String javaBinary = Paths.get(
            System.getProperty("java.home"),
            "bin",
            System.getProperty("os.name").toLowerCase().startsWith("windows") ? "java.exe" : "java"
        ).toString();
        APERuntime runtime = APERuntime.builder()
            .binary(Paths.get(javaBinary))
            .shellWrapper(false)
            .environment("APEBIND_RUNTIME_TEST", "visible")
            .build();
        APEClient client = new APEClient(
            "fixture.com",
            runtime,
            Map.of(),
            Map.of("env_unset", List.of("APEBIND_TEST_SECRET"))
        );

        List<String> prefixed = new APEClient(
            "fixture.com",
            runtime.toBuilder().launcher("loader", "--flag").build(),
            Map.of(),
            Map.of()
        ).commandLine(List.of("-version"));
        boolean commandLineOk = prefixed.equals(List.of("loader", "--flag", javaBinary, "-version"));

        Map<String, String> environment = client.environment();
        boolean environmentOk = "visible".equals(environment.get("APEBIND_RUNTIME_TEST"))
            && !environment.containsKey("APEBIND_TEST_SECRET");

        List<String> lines = new CopyOnWriteArrayList<>();
        List<String> prompts = new CopyOnWriteArrayList<>();
        CountDownLatch prompted = new CountDownLatch(1);
        ProcessSession session = client.rawPersistent(List.of(
            "-cp",
            System.getProperty("java.class.path"),
            "Prompter"
        ));
        session.onStdoutPrompt(prompt -> {
            prompts.add(prompt);
            prompted.countDown();
        });
        boolean promptSeen = prompted.await(5, TimeUnit.SECONDS);
        session.onStdoutLine(lines::add);
        boolean pidOk = session.pid() > 0;
        int exit = session.waitFor();

        System.out.println(
            commandLineOk + "|" + environmentOk + "|" + promptSeen + "|" + prompts + "|" + lines + "|" + pidOk + "|" + exit
        );
    }
}
''',
        encoding='utf-8',
    )
    subprocess.run(
        [JAVAC, '--release', '17', '-cp', str(classes_directory), '-d', str(classes_directory), str(prompter), str(main)],
        check=True,
        capture_output=True,
        text=True,
        encoding='utf-8',
        errors='replace',
        timeout=120,
    )

    completed = subprocess.run(
        [JAVA, '-cp', str(classes_directory), 'Main'],
        cwd=tmp_path,
        env={**os.environ, 'APEBIND_TEST_SECRET': 'hidden'},
        check=True,
        capture_output=True,
        text=True,
        encoding='utf-8',
        errors='replace',
        timeout=60,
    )

    assert completed.stdout.strip() == (
        'true|true|true|[code: ]|[first, second, code: , visible|null]|true|0'
    )


@pytest.mark.skipif(JAVA is None or JAVAC is None, reason='Java 17+ is not installed')
def test_java_json_keeps_integer_literals_as_longs(tmp_path: Path):
    sources = generate_with_synthetic_ape(tmp_path)
    classes_directory = tmp_path / 'classes'
    classes_directory.mkdir()
    generated = sorted(sources.glob('*.java'))
    subprocess.run(
        [JAVAC, '--release', '17', '-d', str(classes_directory), *map(str, generated)],
        check=True,
        capture_output=True,
        text=True,
        encoding='utf-8',
        errors='replace',
        timeout=120,
    )
    main = tmp_path / 'Main.java'
    main.write_text(
        '''
import apebind.generated.fixturebind.Json;
import java.util.Map;

public class Main {
    public static void main(String[] args) {
        Map<String, Object> parsed = Json.object(Json.parse("{\\"size\\":20480,\\"ratio\\":0.5,\\"big\\":1e3}"));
        System.out.println(
            parsed.get("size").getClass().getSimpleName() + "|"
                + parsed.get("ratio").getClass().getSimpleName() + "|"
                + parsed.get("big").getClass().getSimpleName() + "|"
                + Json.stringify(parsed)
        );
    }
}
''',
        encoding='utf-8',
    )
    subprocess.run(
        [JAVAC, '--release', '17', '-cp', str(classes_directory), '-d', str(classes_directory), str(main)],
        check=True,
        capture_output=True,
        text=True,
        encoding='utf-8',
        errors='replace',
        timeout=120,
    )

    completed = subprocess.run(
        [JAVA, '-cp', str(classes_directory), 'Main'],
        cwd=tmp_path,
        check=True,
        capture_output=True,
        text=True,
        encoding='utf-8',
        errors='replace',
        timeout=60,
    )

    # A primitive conditional in the parser once promoted every integer literal to double.
    assert completed.stdout.strip() == 'Long|Double|Double|{"size":20480,"ratio":0.5,"big":1000.0}'
